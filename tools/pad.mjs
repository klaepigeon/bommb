// Drive the game with a fake controller through the native bridge (as the Android app does).
import { createRequire } from 'node:module';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 960, height: 540 } });
const errors = []; p.on('pageerror', (e) => errors.push(e.stack));
await p.goto(pathToFileURL(join(root, 'dist/index.html')).href + '?q=low');
await p.waitForFunction(() => window.__ready, null, { timeout: 200000 });
const pad = (o = {}, ms = 1500) => p.evaluate(([o]) => window.__nativePad(o.lx || 0, o.ly || 0, o.rx || 0, o.ry || 0, 0, 0, o.mask || 0), [o]).then(() => p.waitForTimeout(ms));
const B = { A: 1, B: 2, X: 4, Y: 8, START: 512, DOWN: 1 << 13 };
let fails = 0; const check = (label, ok, v) => { if (!ok) fails++; console.log((ok ? 'ok  ' : 'FAIL') + ' ' + label.padEnd(26) + ' ' + JSON.stringify(v)); };
await pad({ mask: B.A }); await pad({});
check('A starts the game', await p.evaluate(() => window.__G.running), await p.evaluate(() => document.getElementById('start').className));
const x0 = await p.evaluate(() => window.__P.pos.x);
await pad({ ly: -1 }, 6000); await pad({});
const x1 = await p.evaluate(() => window.__P.pos.x);
check('left stick walks', Math.abs(x1 - x0) > 0.2, [x0.toFixed(2), x1.toFixed(2)]);
const y0 = await p.evaluate(() => window.__P.yaw); await pad({ rx: 1 }, 4000); await pad({});
check('right stick looks', Math.abs((await p.evaluate(() => window.__P.yaw)) - y0) > 0.2, null);
await pad({ mask: B.X }); await pad({});
check('X torch', await p.evaluate(() => window.__G.torch.on), null);
check('prompt shows A', await p.evaluate(() => (document.getElementById('prompt').innerHTML.match(/<kbd>(.*?)<\/kbd>/) || [])[1] ?? 'none') !== 'E', await p.evaluate(() => document.getElementById('prompt').innerHTML));
await pad({ mask: B.START }); await pad({});
check('Start pauses', await p.evaluate(() => !window.__G.running && !document.getElementById('pause').classList.contains('hidden')), null);
await pad({ mask: B.DOWN }); await pad({});
await pad({ mask: B.B }); await pad({});
check('B resumes', await p.evaluate(() => window.__G.running), null);
await p.evaluate(() => window.__back()); await p.waitForTimeout(1500);
check('Android back pauses', await p.evaluate(() => !window.__G.running), null);
console.log(errors.length ? 'ERRORS\n' + errors.join('\n') : 'no errors', `| ${fails} failed`);
await b.close(); process.exit(errors.length || fails ? 1 : 0);
